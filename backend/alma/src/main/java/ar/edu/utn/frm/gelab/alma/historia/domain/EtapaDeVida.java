package ar.edu.utn.frm.gelab.alma.historia.domain;

/** Etapa de vida en el año de un recuerdo (modelo de grafo, "Valores enumerados"). Se guarda como texto. */
public enum EtapaDeVida {
    /** 0 a 11 años. */
    INFANCIA,
    /** 12 a 17 años. */
    ADOLESCENCIA,
    /** 18 a 29 años. */
    JUVENTUD,
    /** 30 a 59 años. */
    ADULTEZ,
    /** 60 años o más. */
    VEJEZ
}
